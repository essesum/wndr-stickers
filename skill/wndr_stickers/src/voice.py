"""Голос бота — всё, что он говорит людям, в одном месте.

Раньше эти фразы были размазаны по обработчикам и писались по ходу дела. Здесь
они собраны, чтобы характер бота можно было прочитать и поправить целиком, не
выискивая строки по коду.

Тон — из самого WNDR Club: движение, а не отчёт о работе. Бот не объясняет
человеку, что у него внутри плашка и провайдер; он говорит, что делает, и
делает. Meta-skill клуба — действие: не ждать идеальных условий, а двигаться
вперёд. Бот разговаривает так же.
"""
from __future__ import annotations

import random

#: Пока идёт генерация. Человек ждёт около минуты, и всё это время сообщение
#: висит у него перед глазами — поэтому оно живое, а не «выполняется запрос».
WAITING: tuple[str, ...] = (
    "Колдую над стикером…",
    "Творю…",
    "Замешиваю цвет и смысл…",
    "Собираю фразу в форму…",
    "Уже делаю, дай минутку…",
    "Ищу этой фразе её вид…",
    "Кручу, верчу, примеряю…",
    "Делаю. Не идеально — зато по-настоящему…",
    "Пошло дело…",
)


def waiting(rng: random.Random | None = None) -> str:
    """Фраза ожидания. Каждый раз новая, чтобы бот не звучал автоответчиком."""
    return (rng or random.Random()).choice(WAITING)


#: Когда стикер готов. Раньше тут был машинный отчёт «форма lightning · кегль
#: 133» — человеку это ничего не даёт.
DONE: tuple[str, ...] = (
    "Готово: «{phrase}»",
    "Держи: «{phrase}»",
    "Вот: «{phrase}»",
    "Сделал: «{phrase}»",
    "Получилось: «{phrase}»",
)


def done(phrase: str, rng: random.Random | None = None) -> str:
    return (rng or random.Random()).choice(DONE).format(phrase=phrase)


def failed() -> str:
    """Не получилось. Вина не на человеке, и он знает, что делать дальше."""
    return "Не вышло на этот раз. Попробуй ещё раз — иногда со второго заходит."


#: Справка. Бот не собеседник: его дело — делать контент. Отвечает коротко,
#: по делу, и возвращается к работе.
HELP = """\
Делаю стикеры <b>WNDR</b>. Пришли фразу — верну готовый стикер.

• фраза → стикер
• <code>Это не *тантра*</code> — слово в звёздочках станет оранжевым
• «что в паке» — покажу, что уже есть
• «убери из пака "фраза"» — свой уберу сразу, за чужой соберу голоса

Свой стикер твой: кладёшь и убираешь сам. Чужой в одиночку не убрать.
Удаление окончательное — передумал, сделай новый.
В общем чате пиши через тег."""

_INVITE = '\n\nСделать стикер из «{phrase}»? Напиши <code>!{phrase}</code>'


def help_text(asked: str | None = None) -> str:
    """Справка. Если человек что-то спросил — предлагаем сделать стикер из этого же.

    Живой случай: «что ты умеешь?» ушло на стикер вместо ответа. Теперь бот
    отвечает, но не отнимает возможность — вдруг фраза и правда нужна.
    """
    text = HELP
    if asked and asked.strip():
        text += _INVITE.format(phrase=asked.strip())
    return text
